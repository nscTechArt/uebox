/**
 * 「模型」页这几个弹窗谁压谁。
 *
 * 不写这几个数会怎样：ant 的 Modal 默认全是 z-index 1000，谁在上面就由
 * **body 里的 DOM 先后**决定 —— 而那个先后是「本次会话里谁先被打开过一次」
 * （Modal 首次打开才创建 teleport 容器，之后一直复用）。
 *
 * 于是就有了这个 bug：先从设置页点「+ 添加 Provider」开过目录，再点一张
 * 卡片进管理弹窗，这时候在管理弹窗里点「+ 添加 Provider」，目录复用的是
 * 那个更早创建的容器 —— 弹出来却在管理弹窗**后面**，看上去像点了没反应。
 * 反过来先开管理弹窗又是好的。同一段代码两种表现，取决于用户先点了哪儿。
 *
 * 所以层级必须显式钉死，而不是交给打开顺序。
 */

/**
 * 层与层之间留 100 而不是紧挨着：ant 的浮层（下拉、tooltip）默认取
 * 基准 + 50，管理弹窗里的「接口协议」「思考档位」这些下拉就落在 1050。
 * 层号排太密，下拉会卡在两层弹窗中间。
 */

/** 服务商（管理弹窗）—— 最底下那层，就是 ant 的默认基准 */
export const Z_MANAGER = 1000

/** 添加 Provider（目录）—— 它是管理弹窗里的一步，永远压在管理弹窗上面 */
export const Z_CATALOG = 1100

/** 各种确认框（未保存拦截、删除确认）—— 上面任何一层都可能弹它，所以在最顶上 */
export const Z_CONFIRM = 1200
